// --- Browser agent observation contract (Issue 24) -------------------------
//
// When browser agents observe the live site, they write structured observations
// to the run directory. These observations are interchangeable with fixture data —
// deterministic stages read through an InputProvider seam and cannot distinguish
// between observations and recorded fixtures.

export const OBSERVATION_STATUSES = ['present', 'absent', 'blocked', 'error'] as const;
export type ObservationStatus = (typeof OBSERVATION_STATUSES)[number];

export const OBSERVATION_CONTENT_TYPES = ['html', 'scripts', 'json', 'text', 'candidates'] as const;
export type ObservationContentType = (typeof OBSERVATION_CONTENT_TYPES)[number];

/**
 * A page observation written by a browser agent to the run directory.
 * Captures what a page source yielded, with explicit status for unobtainable sources.
 * Never omits observations, never fabricates content, never executes instruction-like text.
 */
export type PageObservation = {
  /** Unique identifier for this observation */
  observation_id: string;
  /** Which extractor (URL discovery) or observation kind (behavior/interaction/product) this observation is for */
  extractor_id: ExtractorId | ObservationKind;
  /** The page URL that was observed */
  page_url: string;
  /** Whether content was obtainable */
  status: ObservationStatus;
  /** Type of content (html, scripts, json, text, or pre-resolved candidates) */
  content_type: ObservationContentType;
  /** The content itself (only present if status is 'present') */
  content?: string | string[];
  /** Reason if blocked or error (e.g., 'login_required', 'geo_block', 'network_error') */
  reason?: string;
  /** When this observation was recorded */
  timestamp: string;
};

/**
 * Metadata tracking which provider was used for a run's observations.
 * Allows runs to declare whether they used recorded fixtures or live observations.
 */
export type ObservationProviderMetadata = {
  provider_type: 'fixture_recorded' | 'live_browser';
  provider_name?: string;
  observations_path?: string;
};

