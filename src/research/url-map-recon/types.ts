// --- Extractor input/output ------------------------------------------------
//
// Extractors are pure TS functions. In production they run inside the page via
// browser_evaluate; offline/in-repo they take an already-supplied text/array
// snapshot. The return type structurally cannot carry the raw input back out —
// only `urls`, `status`, and `error`.

export type ExtractorInput = {
  pageUrl: string;
  params?: Record<string, unknown>;
  /** raw HTML snapshot supplied by the caller (never echoed back) */
  html?: string;
  /** script bodies supplied by the caller (never echoed back) */
  scripts?: string[];
  /** JSON/config text supplied by the caller (never echoed back) */
  json?: string;
  /** plain text supplied by the caller, e.g. robots.txt / sitemap.xml body */
  text?: string;
  /** pre-resolved candidate URL/path strings (e.g. Performance API entries, or any observation recorded with content_type "candidates") */
  candidates?: string[];
  /** id of the PageObservation this input was built from, when it came from one (Issue 29 provenance) */
  observationId?: string;
  /**
   * Recorded-fixture signal that this step's source could not be reached as
   * a source (not merely "reached and found zero"): `absent` when the
   * resource itself doesn't exist (e.g. sitemap.xml 404), `blocked` when an
   * auth gate stopped access before extraction could run.
   */
  sourceStatus?: 'absent' | 'blocked';
};

export type ExtractorStatus = 'ok' | 'empty' | 'error';

export type ExtractorResult = {
  status: ExtractorStatus;
  urls: string[];
  rejectedCount: number;
  error?: string;
};

export type ExtractorFn = (input: ExtractorInput) => ExtractorResult;

// --- Extractor input contracts (Issue 29) -----------------------------------
//
// Splits extractor *input* (what raw shape a source-specific parser is willing to
// parse) from extractor *output* (the URLs it produces). A `candidates` observation
